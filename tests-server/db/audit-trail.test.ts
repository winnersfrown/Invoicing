// The evidence trail is permanent: append-only tables, undeletable invoices, server-only queues.
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createTestDb, seedTwoOrgs, type TestDb, type TwoOrgs } from './harness';
import { ORG_TABLES, PRIVILEGED_ONLY, expectDenied, rowsChanged, seedGraph, snapshot, type Graph } from './fixtures';

let t: TestDb;
let s: TwoOrgs;
let a: Graph;

beforeAll(async () => {
  t = await createTestDb();
  s = await seedTwoOrgs(t);
  a = await seedGraph(t, s.orgA);
});
afterAll(() => t.close());

const RESTRICT = { code: '23001' }; // restrict_violation from ON DELETE RESTRICT
const APPEND_ONLY = ORG_TABLES.filter((x) => x.appendOnly);

describe('append-only tables reject update and delete for every role', () => {
  it('covers exactly audit_events, resolution_actions, tool_calls and supplier_message_drafts', () => {
    expect(APPEND_ONLY.map((x) => x.table).sort()).toEqual(['audit_events', 'resolution_actions', 'supplier_message_drafts', 'tool_calls']);
  });

  describe.each(APPEND_ONLY)('$table', (spec) => {
    it('privileged connection cannot update', async () => {
      await expect(t.asService((tx) => tx.query(`update ${spec.table} set ${spec.set} where ${spec.key(a)}`))).rejects.toThrow(/append-only/);
    });
    it('privileged connection cannot delete', async () => {
      await expect(t.asService((tx) => tx.query(`delete from ${spec.table} where ${spec.key(a)}`))).rejects.toThrow(/append-only/);
    });
    it('privileged connection cannot truncate', async () => {
      await expect(t.asService((tx) => tx.query(`truncate ${spec.table} cascade`))).rejects.toThrow(/append-only/);
    });
    it.each(['admin', 'reviewer'] as const)('%s cannot update or delete', async (role) => {
      const before = await snapshot(t, spec, a);
      expect(await rowsChanged(t, s.orgA[role], `update ${spec.table} set ${spec.set} where ${spec.key(a)}`)).toBe(0);
      expect(await rowsChanged(t, s.orgA[role], `delete from ${spec.table} where ${spec.key(a)}`)).toBe(0);
      expect(await snapshot(t, spec, a)).toEqual(before);
    });
    it('the seeded row is still intact afterwards', async () => {
      expect(await snapshot(t, spec, a)).not.toBeNull();
    });
  });

  it('audit_events ids are generated by the database and cannot be supplied', async () => {
    await expect(t.asService((tx) => tx.query(
      `insert into audit_events (id, organization_id, actor_type, event_type, target_type, target_id) values (1, $1, 'system', 'x', 'x', 'x')`,
      [s.orgA.id]))).rejects.toThrow();
  });
});

describe('invoices are never deleted', () => {
  it.each(['admin', 'reviewer'] as const)('%s cannot delete an invoice', async (role) => {
    expect(await rowsChanged(t, s.orgA[role], `delete from invoices where id = '${a.invoice}'`)).toBe(0);
    const r = await t.asService((tx) => tx.query('select 1 from invoices where id = $1', [a.invoice]));
    expect(r.rows).toHaveLength(1);
  });

  it('admin cannot delete even a freshly uploaded invoice with no evidence attached', async () => {
    const id = await t.asUser(s.orgA.reviewer, async (tx) => (await tx.query<{ id: string }>(
      `insert into invoices (organization_id, status, document_storage_path, document_sha256, extraction, created_by)
       values ($1, 'uploaded', 'p', repeat('d', 64), '{}', $2) returning id`, [s.orgA.id, s.orgA.reviewer])).rows[0].id);
    expect(await rowsChanged(t, s.orgA.admin, `delete from invoices where id = '${id}'`)).toBe(0);
  });

  it.each([
    ['discrepancies', `insert into discrepancies (organization_id, invoice_id, discrepancy_type, severity, status,
      deterministic_evidence, evidence_hash) values ($1, $2, 'line_arithmetic', 'low', 'open', '{}', 'h')`],
    ['invoice_line_items', `insert into invoice_line_items (invoice_id, line_number, description, quantity, unit_price, line_total)
      select $2::uuid, 1, 'd', 1, 1, 1 where $1::uuid is not null`],
  ])('privileged delete of an invoice is blocked while %s reference it', async (_child, childSql) => {
    const inv = await t.asService(async (tx) => {
      const id = (await tx.query<{ id: string }>(
        `insert into invoices (organization_id, status, document_storage_path, document_sha256, extraction, created_by)
         values ($1, 'uploaded', 'p', repeat('e', 64), '{}', $2) returning id`, [s.orgA.id, s.orgA.reviewer])).rows[0].id;
      await tx.query(childSql, [s.orgA.id, id]);
      return id;
    });
    await expect(t.asService((tx) => tx.query('delete from invoices where id = $1', [inv]))).rejects.toMatchObject(RESTRICT);
  });

  it('privileged delete of a discrepancy is blocked while a resolution action references it', async () => {
    await expect(t.asService((tx) => tx.query('delete from discrepancies where id = $1', [a.discrepancy])))
      .rejects.toMatchObject(RESTRICT);
  });
});

describe('jobs and idempotency_keys are only for the privileged connection', () => {
  it.each(PRIVILEGED_ONLY)('authenticated admin cannot select from %s', async (table) => {
    await expectDenied(t.asUser(s.orgA.admin, (tx) => tx.query(`select * from ${table}`)));
  });

  it('authenticated admin cannot insert a job', async () => {
    await expectDenied(t.asUser(s.orgA.admin, (tx) => tx.query(
      `insert into jobs (organization_id, kind, payload, idempotency_key) values ($1, 'x', '{}', 'k-auth')`, [s.orgA.id])));
  });

  it('authenticated admin cannot insert an idempotency key', async () => {
    await expectDenied(t.asUser(s.orgA.admin, (tx) => tx.query(
      `insert into idempotency_keys (organization_id, key, endpoint, user_id, response, status_code)
       values ($1, 'k-auth', 'POST /x', $2, '{}', 200)`, [s.orgA.id, s.orgA.admin])));
  });

  it.each(PRIVILEGED_ONLY)('authenticated admin cannot update or delete %s', async (table) => {
    expect(await rowsChanged(t, s.orgA.admin, `update ${table} set organization_id = organization_id`)).toBe(0);
    expect(await rowsChanged(t, s.orgA.admin, `delete from ${table}`)).toBe(0);
    const r = await t.asService((tx) => tx.query(`select 1 from ${table} where organization_id = $1`, [s.orgA.id]));
    expect(r.rows.length).toBeGreaterThan(0);
  });

  it('the privileged connection can enqueue and claim a job with sensible defaults', async () => {
    const job = await t.asService(async (tx) => (await tx.query<{ id: string; status: string; attempts: number; updated_at: Date }>(
      `insert into jobs (organization_id, kind, payload, idempotency_key) values ($1, 'process_invoice', '{}', 'k-svc')
       returning id, status, attempts, updated_at`, [s.orgA.id])).rows[0]);
    expect(job).toMatchObject({ status: 'queued', attempts: 0 });
    // the trigger overrides any supplied updated_at with the server's time
    const after = await t.asService(async (tx) => (await tx.query<{ updated_at: Date }>(
      `update jobs set status = 'running', attempts = attempts + 1, updated_at = '2000-01-01' where id = $1 returning updated_at`,
      [job.id])).rows[0]);
    expect(after.updated_at.getTime()).toBeGreaterThanOrEqual(job.updated_at.getTime());
  });

  it('updated_at on invoices is set by trigger and cannot be backdated', async () => {
    const before = await t.asService(async (tx) =>
      (await tx.query<{ updated_at: Date }>('select updated_at from invoices where id = $1', [a.invoice])).rows[0]);
    const after = await t.asService(async (tx) => (await tx.query<{ updated_at: Date }>(
      `update invoices set status = 'validated', updated_at = '2000-01-01' where id = $1 returning updated_at`, [a.invoice])).rows[0]);
    expect(after.updated_at.getTime()).toBeGreaterThanOrEqual(before.updated_at.getTime());
  });
});
